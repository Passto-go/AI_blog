-- ============================================================================
-- 文章作者字段（author）
-- 目的：让每篇文章可单独指定作者；后台编辑器新增「作者」输入框，
--       前台文章列表行/文章页可展示作者（留空则回退显示站点默认作者）。
-- 在 Supabase 后台 → SQL Editor 执行本文件（一次性，幂等，可重复执行）。
-- ============================================================================

alter table posts add column if not exists author text not null default '';

-- 可选：把历史「空作者」回填为站点默认作者。
-- 默认作者见 src/data/site.js 的 site.author（当前为「老一贯」）。
-- 若希望历史文章继续走「前端回退显示」而不写库，可注释掉下面这行。
update posts set author = '老一贯' where author is null or author = '';
